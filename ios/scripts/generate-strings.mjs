// Generates Sources/ZellioChatCore/Generated/ChatStringTable.swift from ../design/strings.json.
// Run: node scripts/generate-strings.mjs        (write)
//      node scripts/generate-strings.mjs --check (exit 1 when the checked-in file is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(join(root, '..', 'design', 'strings.json'), 'utf8'));
const target = join(root, 'Sources', 'ZellioChatCore', 'Generated', 'ChatStringTable.swift');

const BS = String.fromCharCode(92);
// JSON escapes control characters as backslash-u-XXXX. Swift needs backslash-u-{XXXX}.
const literal = (value) => JSON.stringify(value)
  .split(BS + 'u')
  .map((part, index) => (index === 0 ? part : `${BS}u{${part.slice(0, 4)}}${part.slice(4)}`))
  .join('');
const table = (locale) => Object.keys(source[locale]).sort()
  .map((key) => `        ${literal(key)}: ${literal(source[locale][key])},`).join('\n');

const output = `// GENERATED by scripts/generate-strings.mjs from sdks/design/strings.json. Do not edit by hand.

enum ChatStringTable {
    static let en: [String: String] = [
${table('en')}
    ]

    static let ar: [String: String] = [
${table('ar')}
    ]
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (current !== output) { console.error('ChatStringTable.swift is stale. Run: node scripts/generate-strings.mjs'); process.exit(1); }
} else {
  writeFileSync(target, output);
}
